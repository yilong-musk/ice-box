export function drawIcon(p, name, x, y, ink) {
  const c = hex(ink);
  const rows = GLYPHS[name];
  for (let row = 0; row < rows.length; row++) {
    for (let col = 0; col < rows[row].length; col++) {
      if (rows[row][col] === "#") p.px(x + col, y + row, c);
    }
  }
}

export function draw(p, _t, o) {
  const ink = o.ink || "#151a3d";
  if (o.icon) {
    drawIcon(p, o.icon, 0, 0, ink);
    return;
  }
  ICONS.forEach((name, i) => drawIcon(p, name, 4 + i * 18, 4, ink));
}
