// Render the navigation glyphs out of a pixelfx checkout.
//
//   node docs/brand/nav-icons/tools/export.mjs <pixelfx checkout>
//
// Copies fx/nav-icons.js to <pixelfx>/src/fx/ui/nav-icons.js, then writes:
//   assets/<name>.png, <name>@4x.png   one ink, for the README
//   apps/desktop/src/components/navGlyphs.ts
//                                      the same grids; the app fills them with
//                                      the button's text color
import { pathToFileURL, fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";

const SIZE = 16;
const INK = "#151a3d";

const pixelfx = process.argv[2];
if (!pixelfx) {
  console.error("usage: node export.mjs <pixelfx checkout>");
  process.exit(1);
}
const root = resolve(pixelfx);
const here = dirname(fileURLToPath(import.meta.url));
const brand = join(here, "..");
const repo = join(here, "..", "..", "..", "..");
const fxSrc = join(brand, "fx", "nav-icons.js");
const fxDest = join(root, "src", "fx", "ui", "nav-icons.js");

mkdirSync(dirname(fxDest), { recursive: true });
copyFileSync(fxSrc, fxDest);

const lib = await import(pathToFileURL(join(root, "tools/lib/fxlib.mjs")).href);
const { encodePNG } = await import(pathToFileURL(join(root, "tools/lib/png.mjs")).href);
const fx = await lib.loadEffect("ui/nav-icons");

function crop(rgba, w, m, W, H) {
  const o = new Uint8ClampedArray(W * H * 4);
  for (let y = 0; y < H; y++) o.set(rgba.subarray(((y + m) * w + m) * 4, ((y + m) * w + m + W) * 4), y * W * 4);
  return o;
}

function centerInk(px, w, h, size) {
  let x0 = w, y0 = h, x1 = -1, y1 = -1;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (px[(y * w + x) * 4 + 3] === 0) continue;
      if (x < x0) x0 = x;
      if (y < y0) y0 = y;
      if (x > x1) x1 = x;
      if (y > y1) y1 = y;
    }
  }
  if (x1 < 0) throw new Error("icon drew nothing");
  const bw = x1 - x0 + 1, bh = y1 - y0 + 1;
  if (bw > size || bh > size) throw new Error(`icon ink ${bw}x${bh} does not fit ${size}px`);
  const ox = Math.floor((size - bw) / 2), oy = Math.floor((size - bh) / 2);
  const o = new Uint8ClampedArray(size * size * 4);
  for (let y = 0; y < bh; y++) {
    o.set(px.subarray(((y0 + y) * w + x0) * 4, ((y0 + y) * w + x0 + bw) * 4), ((oy + y) * size + ox) * 4);
  }
  return o;
}

const names = fx.mod.ICONS;
const glyphs = fx.mod.GLYPHS;
if (!names?.length || !glyphs) throw new Error("nav-icons.js must export ICONS and GLYPHS");

const assets = join(brand, "assets");
mkdirSync(assets, { recursive: true });

for (const name of names) {
  const rows = glyphs[name];
  if (!rows || rows.length !== SIZE || rows.some((row) => row.length !== SIZE)) {
    throw new Error(`${name} is not a ${SIZE}x${SIZE} grid`);
  }
  const [W, H] = fx.meta.size;
  const r = lib.renderFrames(fx, {
    fps: 1,
    bg: "none",
    actor: false,
    options: { icon: name, ink: INK },
  });
  const raw = crop(r.frames[0].clear, r.w, r.margin, W, H);
  const px = centerInk(raw, W, H, SIZE);
  writeFileSync(join(assets, `${name}.png`), encodePNG(SIZE, SIZE, px));
  writeFileSync(join(assets, `${name}@4x.png`), encodePNG(SIZE * 4, SIZE * 4, lib.upscale(px, SIZE, SIZE, 4)));
  console.log(`${name}  ${SIZE}px`);
}

const body = names
  .map((name) => {
    const rows = glyphs[name].map((row) => `    "${row}",`).join("\n");
    return `  ${name}: [\n${rows}\n  ],`;
  })
  .join("\n");
const ts = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by docs/brand/nav-icons/tools/export.mjs. Do not edit.
// One ink. The menu button's text color fills the marks.

export const NAV_GLYPHS = {
${body}
} as const;

export type NavGlyphName = keyof typeof NAV_GLYPHS;
`;
writeFileSync(join(repo, "apps", "desktop", "src", "components", "navGlyphs.ts"), ts);
console.log("navGlyphs.ts");
